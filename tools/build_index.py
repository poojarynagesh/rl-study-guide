"""Build assets/search-index.js from the site's HTML pages.

Run after adding or editing a page:  python tools/build_index.py

The index lists every h2/h3 heading, algorithm box and named equation, each
linked to the nearest heading anchor. Heading ids are derived with the same
slug rule site.js uses, so the anchors line up.
"""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

PAGES = [
    ("home", "index.html"),
    ("roadmap", "roadmap.html"),
    ("ch01", "chapters/ch01.html"),
    ("ch02", "chapters/ch02.html"),
    ("ch03", "chapters/ch03.html"),
    ("ch04", "chapters/ch04.html"),
    ("ch05", "chapters/ch05.html"),
    ("ch06", "chapters/ch06.html"),
    ("ch07", "chapters/ch07.html"),
    ("ch09", "chapters/ch09.html"),
    ("algorithms", "algorithms.html"),
    ("hyper", "hyperparameters.html"),
    ("formulas", "formulas.html"),
    ("quiz", "quiz.html"),
]

TOKEN = re.compile(
    r'<h([23])([^>]*)>(.*?)</h\1>'
    r'|<span class="name">(.*?)</span>'
    r'|<div class="eq-name"><span>(.*?)</span>',
    re.S,
)


def text(fragment):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", "", fragment))).strip()


def slug(s):
    s = re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")
    return s[:60]


def page_title(src):
    m = re.search(r"<title>(.*?)</title>", src, re.S)
    return text(m.group(1)).split(" — ")[0] if m else ""


def main():
    available, entries = [], []
    for pid, rel in PAGES:
        path = ROOT / rel
        if not path.exists():
            continue
        available.append(pid)
        src = path.read_text(encoding="utf-8")
        where = page_title(src)
        anchor = ""
        for m in TOKEN.finditer(src):
            if m.group(1):
                attrs, label = m.group(2), text(m.group(3))
                idm = re.search(r'id="([^"]+)"', attrs)
                anchor = idm.group(1) if idm else slug(label)
                entries.append({"t": label, "p": where, "u": f"{rel}#{anchor}"})
            else:
                label = text(m.group(4) or m.group(5))
                kind = "Algorithm" if m.group(4) else "Formula"
                entries.append({"t": label, "p": f"{where} · {kind}", "u": f"{rel}#{anchor}" if anchor else rel, "k": kind})
    out = ROOT / "assets" / "search-index.js"
    out.write_text(
        "// Generated by tools/build_index.py — do not edit by hand.\n"
        f"window.RL_AVAILABLE = {json.dumps(available)};\n"
        f"window.RL_SEARCH = {json.dumps(entries, ensure_ascii=False, indent=0)};\n",
        encoding="utf-8",
    )
    print(f"{len(entries)} entries from {len(available)} pages -> {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
